"""Provision the AMI fleet entities on TB *Central* (not the Edge) and
assign them to the edge-r1000-wm6108 Edge instance so Central pushes
them down via gRPC cloud sync.

When the R1000 Edge runs in cloud-attached mode (CLOUD_ROUTING_KEY set
to the routing key of a registered Edge in Central), Central is the
source of truth for all entities. Anything created directly on the Edge
collides with what Central pushes (duplicate-key constraint errors on
sync). The correct workflow: create everything on Central, assign it to
the Edge, Central pushes it down on the next sync tick.

What it does:
  1. Re-uses the LwM2M XMLs already generated by tools/tb_edge_upload_models.py
     (./models/*.xml) and uploads them as LWM2M_MODEL resources on Central.
  2. Re-uses build_profile_body() from tb_edge_provision.py to create the
     AMI_LwM2M_Node device profile, then appends the 4 AMI alarm rules
     from tb_edge_monitoring_setup.py.build_ami_alarms() so alarms ship
     down WITH the profile in one sync.
  3. Creates the 7 ami-esp32c6-XXXX devices with LwM2M NoSec credentials.
  4. Builds and creates the AMI Fleet Health dashboard.
  5. Assigns every resource/profile/device/dashboard to the Edge in
     Central. Edge receives them on next cloud-sync tick.

Skipped here (cleaner to add post-sync once Edge has the default chain):
  - Rule-chain Device Profile-node insertion (would target the EDGE-type
    template rule chain on Central; needs to be done on the chain that's
    already assigned to this Edge).
  - Notification template/rule (those are Central-scoped, not synced).

Idempotent: re-running matches existing entities by name/title and
updates them in place; edge assignment is a POST that's safe to repeat.

Usage:
    python tools/tb_central_provision.py
    python tools/tb_central_provision.py --dry-run
    python tools/tb_central_provision.py --edge-name edge-r1000-wm6108
"""
